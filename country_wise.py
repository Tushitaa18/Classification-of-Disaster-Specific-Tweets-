# 1. Define the preprocess_text function to clean and tokenize text.
def preprocess_text(text):
    text = str(text).lower()
    text = re.sub(r"http\S+|www\S+", "", text)  # Remove URLs
    text = re.sub(r"@\w+", "", text)            # Remove mentions
    text = re.sub(r"#\w+", "", text)            # Remove hashtags
    text = re.sub(r"\d+", "", text)             # Remove numbers
    # Corrected: Use str.translate for robust punctuation removal
    text = text.translate(str.maketrans('', '', string.punctuation)) # Remove punctuation
    text = re.sub(r"\s+", " ", text).strip()    # Remove extra spaces
    return text.split()

# 2. Define the evaluate_model function
def evaluate_model(name, y_true, y_pred, y_prob, label_names, n_classes):
    accuracy = accuracy_score(y_true, y_pred)
    precision = precision_score(y_true, y_pred, average='weighted', zero_division=0)
    recall = recall_score(y_true, y_pred, average='weighted', zero_division=0)
    f1 = f1_score(y_true, y_pred, average='weighted', zero_division=0)

    # --- Check for single-class test sets before ROC calculation ---
    if len(np.unique(y_true)) < 2:
        print(f"Warning: Skipping Macro AUC for {name} - only one unique class found in true labels.")
        return {
            "Model": name,
            "Accuracy": accuracy,
            "Precision": precision,
            "Recall": recall,
            "F1-score": f1,
            "Macro AUC": np.nan
        }

    # --- Robustly ensure y_prob has n_classes columns ---
    y_prob_processed = np.asarray(y_prob)
    if y_prob_processed.ndim == 1:
        # If 1D, assume it's probability of positive class for binary or single-class output
        if n_classes == 2:
            y_prob_processed = np.hstack((1 - y_prob_processed.reshape(-1, 1), y_prob_processed.reshape(-1, 1)))
        else: # For multi-class, a 1D array is problematic, assume it's prob of class 0 and pad
            y_prob_processed = np.zeros((y_prob_processed.shape[0], n_classes))
            y_prob_processed[:, 0] = y_prob_processed # Assign what's available to first col
            print(f"Warning: {name} probabilities were 1D for multi-class problem. Padded with zeros assuming class 0 probabilities.")
    elif y_prob_processed.shape[1] == 1 and n_classes == 2:
        # Binary classification where only positive class probability is provided
        y_prob_processed = np.hstack((1 - y_prob_processed, y_prob_processed))
    elif y_prob_processed.shape[1] < n_classes:
        # Fewer columns than expected, pad with zeros for missing class probabilities
        temp_y_prob = np.zeros((y_prob_processed.shape[0], n_classes))
        temp_y_prob[:, :y_prob_processed.shape[1]] = y_prob_processed # Copy existing columns
        y_prob_processed = temp_y_prob
        print(f"Warning: {name} probabilities padded. Predicted {y_prob_processed.shape[1]} columns, expected {n_classes}.")
    elif y_prob_processed.shape[1] > n_classes:
        # More columns than expected, truncate
        y_prob_processed = y_prob_processed[:, :n_classes]
