unique_sources = df['source'].unique()

"""**Reasoning**:
Now that the helper functions are defined, I will implement the main classification pipeline to iterate through each unique disaster source, apply Bag-of-Words feature extraction, train and evaluate the specified classification models, and store all performance metrics and visualizations as instructed.


"""

for source in unique_sources:
    print(f"\n{'='*50}\nProcessing Source: {source}\n{'='*50}")

    df_source = df[df['source'] == source].copy()

    # Skip if not enough data or unique labels for stratification
    if df_source.empty or df_source['merged_label'].nunique() < 2:
        print(f"Skipping {source}: Not enough data or unique labels for classification.")
        continue

    # Encode labels for the current source
    le = LabelEncoder()
    y_encoded = le.fit_transform(df_source['merged_label'])
    label_names = le.classes_
    n_classes = len(label_names)

    # Bag-of-Words Feature Extraction
    vectorizer = CountVectorizer(min_df=5) # min_df=5 to avoid extremely rare words
    X_bow = vectorizer.fit_transform(df_source['clean_text'])

    # Train-test split for the current source
    X_train_bow, X_test_bow, y_train, y_test = train_test_split(
        X_bow, y_encoded, test_size=0.2, stratify=y_encoded, random_state=42
    )

    # Define classification models
    models = {
        "Logistic Regression": LogisticRegression(max_iter=1000, solver='liblinear'), # Added solver for better convergence
        "Random Forest": RandomForestClassifier(n_estimators=200, class_weight='balanced', random_state=42, n_jobs=-1),
        "XGBoost": XGBClassifier(eval_metric='mlogloss', random_state=42),
        "CatBoost": CatBoostClassifier(iterations=500, learning_rate=0.1, depth=6, loss_function='MultiClass', verbose=0, random_seed=42)
    }

    for model_name, model in models.items():
        print(f"\nEvaluating BoW + {model_name} for {source}")
        model.fit(X_train_bow, y_train)
        y_pred = model.predict(X_test_bow)
        y_prob = model.predict_proba(X_test_bow)

        print(classification_report(y_test, y_pred, target_names=label_names, zero_division=0))

        # Evaluate and store results
        metrics = evaluate_model(f"BoW + {model_name}", y_test, y_pred, y_prob, label_names, n_classes)
        metrics["Source"] = source
        metrics["Feature Method"] = "Bag-of-Words"
        all_results.append(metrics)

        # Plot confusion matrix
        plot_confusion_matrix(y_test, y_pred, label_names, f"BoW + {model_name} - {source}")

        # Plot multi-class ROC curve
        plot_multiclass_roc(model, X_test_bow, y_test, label_names, n_classes, f"BoW + {model_name} - {source}")

# Convert all_results to a DataFrame for summary
