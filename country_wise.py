# Ensure preprocess_text is defined for this scope
def preprocess_text(text):
    text = str(text).lower()
    text = re.sub(r"http\S+|www\S+", "", text)
    text = re.sub(r"@\w+", "", text)
    text = re.sub(r"#\w+", "", text)
    text = re.sub(r"\d+", "", text)
    text = re.sub(f"[{re.escape(re.punctuation)}]", "", text)
    text = re.sub(r"\s+", " ", text).strip()
    return text.split()

# Helper function to evaluate model performance
def evaluate_model(name, y_true, y_pred, y_prob, label_names, n_classes):
    accuracy = accuracy_score(y_true, y_pred)
    precision = precision_score(y_true, y_pred, average='weighted', zero_division=0)
    recall = recall_score(y_true, y_pred, average='weighted', zero_division=0)
    f1 = f1_score(y_true, y_pred, average='weighted', zero_division=0)

    # Calculate Macro AUC for multiclass (one-vs-rest)
    y_true_bin = label_binarize(y_true, classes=range(n_classes))
    # Ensure y_prob has probabilities for all classes
    if y_prob.shape[1] != n_classes:
        # If the model didn't predict all classes, pad with zeros or handle appropriately
        # For simplicity, if a class is missing, its AUC contribution will be 0
        print(f"Warning: {name} predicted {y_prob.shape[1]} classes, expected {n_classes}")
        # Create a padded y_prob if necessary
        padded_y_prob = np.zeros((y_prob.shape[0], n_classes))
        for i in range(y_prob.shape[1]):
             if i < n_classes: # Ensure we don't go out of bounds for n_classes
                padded_y_prob[:, i] = y_prob[:, i]
        y_prob = padded_y_prob

    fpr = dict()
    tpr = dict()
    roc_auc = dict()
    for i in range(n_classes):
        fpr[i], tpr[i], _ = roc_curve(y_true_bin[:, i], y_prob[:, i])
        roc_auc[i] = auc(fpr[i], tpr[i])

    all_fpr = np.unique(np.concatenate([fpr[i] for i in range(n_classes)]))
    mean_tpr = np.zeros_like(all_fpr)
    for i in range(n_classes):
        mean_tpr += np.interp(all_fpr, fpr[i], tpr[i])
    mean_tpr /= n_classes
    macro_auc = auc(all_fpr, mean_tpr)

    return {
        "Model": name,
        "Accuracy": accuracy,
        "Precision": precision,
        "Recall": recall,
        "F1-score": f1,
        "Macro AUC": macro_auc
    }

# Helper function to plot confusion matrix
def plot_confusion_matrix(y_true, y_pred, labels, title):
    cm = confusion_matrix(y_true, y_pred, normalize='true')
    plt.figure(figsize=(max(8, len(labels)), max(6, len(labels))))
    sns.heatmap(
        cm, annot=True, fmt=".2f", cmap="Greens",
        xticklabels=labels, yticklabels=labels
    )
    plt.title(f'Confusion Matrix: {title}')
    plt.xlabel('Predicted Label')
    plt.ylabel('True Label')
    plt.xticks(rotation=45, ha='right')
    plt.yticks(rotation=0)
    plt.tight_layout()
    plt.show()

# Helper function to plot multiclass ROC curve
def plot_multiclass_roc(model, X_test, y_test, label_names, n_classes, model_name):
    y_score = model.predict_proba(X_test)
    y_test_bin = label_binarize(y_test, classes=range(n_classes))

    fpr = dict()
    tpr = dict()
    roc_auc = dict()

    for i in range(n_classes):
        fpr[i], tpr[i], _ = roc_curve(y_test_bin[:, i], y_score[:, i])
        roc_auc[i] = auc(fpr[i], tpr[i])

    # Aggregate all false positive rates
    all_fpr = np.unique(np.concatenate([fpr[i] for i in range(n_classes)]))

    # Interpolate all ROC curves at these points
    mean_tpr = np.zeros_like(all_fpr)
    for i in range(n_classes):
        mean_tpr += np.interp(all_fpr, fpr[i], tpr[i])

    # Average it and compute AUC
    mean_tpr /= n_classes

    macro_auc = auc(all_fpr, mean_tpr)

    plt.figure(figsize=(10, 8))
    plt.plot(all_fpr, mean_tpr,
             label=f'Macro-average ROC (area = {macro_auc:.2f})',
             color='navy', linestyle=':', linewidth=4)

    colors = cycle(['aqua', 'darkorange', 'cornflowerblue', 'purple', 'red', 'green', 'blue', 'brown', 'pink', 'gray', 'olive', 'cyan'])
    for i, color in zip(range(n_classes), colors):
        plt.plot(fpr[i], tpr[i], color=color, lw=2,
                 label=f'ROC curve of class {label_names[i]} (area = {roc_auc[i]:.2f})')

    plt.plot([0, 1], [0, 1], 'k--', lw=2)
    plt.xlim([0.0, 1.0])
    plt.ylim([0.0, 1.05])
    plt.xlabel('False Positive Rate')
    plt.ylabel('True Positive Rate')
    plt.title(f'Multi-class ROC Curve for {model_name}')
    plt.legend(loc="lower right", fontsize=8)
    plt.tight_layout()
    plt.show()

    return macro_auc

