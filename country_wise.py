    # --- Robustly ensure y_true_bin has n_classes columns ---
    # label_binarize itself should create n_classes columns if `classes` is set correctly.
    y_true_bin_raw = label_binarize(y_true, classes=range(n_classes))
    y_true_bin_processed = np.zeros((len(y_true), n_classes))
    cols_to_copy = min(y_true_bin_raw.shape[1], n_classes) # Ensure not to copy more cols than exist
    y_true_bin_processed[:, :cols_to_copy] = y_true_bin_raw[:, :cols_to_copy]
    if y_true_bin_raw.shape[1] != n_classes:
        print(f"Warning: y_true_bin initially had {y_true_bin_raw.shape[1]} columns, expected {n_classes}. Reshaped for consistency.")
    y_true_bin = y_true_bin_processed

    fpr = dict()
    tpr = dict()
    roc_auc = dict()

    macro_aucs_values = []

    for i in range(n_classes):
        # Now both y_prob_processed and y_true_bin are guaranteed to have n_classes columns.
        # The only remaining condition for roc_curve is if both 0 and 1 are present in y_true_bin[:, i]
        if len(np.unique(y_true_bin[:, i])) > 1:
            fpr[i], tpr[i], _ = roc_curve(y_true_bin[:, i], y_prob_processed[:, i])
            roc_auc[i] = auc(fpr[i], tpr[i])
            macro_aucs_values.append(roc_auc[i])
        else:
            # If only one class is present in y_true_bin[:, i], ROC is undefined.
            # Assign dummy values for plotting and a neutral AUC.
            fpr[i], tpr[i] = [0, 1], [0, 1]
            roc_auc[i] = 0.5
